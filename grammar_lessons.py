def check_lessons():
    """Return a list of problems found in the lesson data (empty list = all good)."""
    problems, seen_ids = [], set()
    used = [i for t in LOWER_TOPICS + UPPER_TOPICS for i in t["lessons"]]
    for lesson_id in _LESSONS:
        if lesson_id not in used:
            problems.append(f"{lesson_id}: not in any topic")
    for level in LEVELS.values():
        placed = [l["id"] for t in level["topics"] for l in t["lessons"]]
        for lesson_id in placed:
            if placed.count(lesson_id) > 1:
                problems.append(f"{lesson_id}: appears twice in one level")
    for lesson in _LESSONS.values():
        lid = lesson["id"]
        if lid in seen_ids:
            problems.append(f"{lid}: duplicate id")
        seen_ids.add(lid)
        for key in ("id", "emoji", "title", "blurb", "codes", "intro", "rules", "tip", "questions"):
            if not lesson.get(key):
                problems.append(f"{lid}: missing {key}")
        for n, q in enumerate(lesson["questions"], 1):
            opts = q["options"]
            if q["kind"] not in ("spot", "use"):
                problems.append(f"{lid} q{n}: kind must be spot or use")
            if len(opts) < 2 or len(set(opts)) != len(opts):
                problems.append(f"{lid} q{n}: options must be 2 or more and all different")
            if not q["why"].strip():
                problems.append(f"{lid} q{n}: missing explanation")
    return problems