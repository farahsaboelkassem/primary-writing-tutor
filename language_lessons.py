"""Language Arts (vocabulary and language) lessons for The Writing Adventure.

HOW TO EDIT
-----------
* Each level (lower / upper) has a list of lessons.
* A lesson has: id, emoji, title, blurb, codes (the framework statements it covers),
  intro, rules (a heading, some text and examples) and a tip.
* Practice questions use Q(kind, question, correct_answer, [wrong answers], explanation).
  - kind is "spot" (reading: find it, understand it) or "use" (writing: apply it).
  - Always type the CORRECT answer first. The app shuffles the answers for the child.
  - Keep the wrong answers believable but clearly wrong.
* Use **double asterisks** for bold. Use ___ for a gap in a question.
* Keep every lesson id unique and do not change ids after children have saved
  progress, because progress is stored against the id.
"""


def Q(kind, question, correct, wrong, why):
    return {"kind": kind, "q": question, "options": [correct] + list(wrong), "why": why}


def R(title, text, examples=()):
    return {"title": title, "text": text, "examples": list(examples)}


